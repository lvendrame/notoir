//! Reference pages of the user guide (`docs/guide/src/reference/`), generated
//! from the command registry, the settings schema and the MCP tool catalogue so
//! they never drift. `cargo run -p notoir --example gen_docs` writes them;
//! `tests/docs.rs` fails when the committed files are stale.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use notoir_core::command::{Category, CommandRegistry, CommandSpec};
use notoir_core::keymap::{KeyBindingDef, KeyChord, Platform};
use notoir_core::settings::{Schema, SettingDef, SettingType, SettingValue};

use crate::core::AppCore;
use crate::i18n::{Language, t_in};
use crate::menus::{DynamicMenu, MenuItem};
use crate::settings_tab::{CATEGORIES, category_key};

const HEADER: &str =
    "<!-- Generated by `cargo run -p notoir --example gen_docs`. Do not edit. -->\n\n";

/// Every generated page: (file name, Markdown).
pub fn render_all() -> Vec<(&'static str, String)> {
    vec![
        ("menus.md", menus()),
        ("shortcuts.md", shortcuts()),
        ("commands.md", commands()),
        ("settings.md", settings()),
        ("mcp-tools.md", mcp_tools()),
    ]
}

fn en(key: &str) -> String {
    t_in(Language::En, key)
}

/// Escapes text for a Markdown table cell.
fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn registry(platform: Platform) -> CommandRegistry<AppCore> {
    let mut r = CommandRegistry::default();
    crate::commands::register_all(&mut r, platform);
    r
}

fn chord(def: &KeyBindingDef, platform: Platform) -> String {
    let src = match platform {
        Platform::Mac => def.mac.unwrap_or(def.key),
        _ => def.key,
    };
    KeyChord::parse(src, platform).map_or_else(|_| src.to_owned(), |c| c.display(platform))
}

fn keys(spec: &CommandSpec<AppCore>, platform: Platform) -> String {
    let mut out: Vec<String> = Vec::new();
    for d in &spec.default_keys {
        let k = format!("`{}`", chord(d, platform));
        // Two bindings can show the same chord on one platform (Redo).
        if !out.contains(&k) {
            out.push(k);
        }
    }
    out.join(", ")
}

fn by_category(r: &CommandRegistry<AppCore>) -> BTreeMap<Category, Vec<&CommandSpec<AppCore>>> {
    let mut out: BTreeMap<Category, Vec<_>> = BTreeMap::new();
    for spec in r.iter() {
        out.entry(spec.category).or_default().push(spec);
    }
    for list in out.values_mut() {
        list.sort_by_key(|s| en(&s.title_key));
    }
    out
}

fn shortcuts() -> String {
    let mac = registry(Platform::Mac);
    let win = registry(Platform::Windows);
    let mut s = String::from(HEADER);
    s.push_str("# Keyboard shortcuts\n\n");
    s.push_str(
        "Default shortcuts. Linux uses the Windows column, with `Super` in place of `Win`. A command can have \
         several shortcuts; two-stroke chords are pressed one after the other. Change them in \
         [Keybindings](../keybindings.md).\n",
    );
    for (cat, specs) in by_category(&mac) {
        let rows: Vec<_> = specs
            .iter()
            .filter(|s| !s.default_keys.is_empty())
            .collect();
        if rows.is_empty() {
            continue;
        }
        let _ = write!(s, "\n## {}\n\n", en(cat.title_key()));
        s.push_str("| Command | macOS | Windows / Linux | When |\n|---|---|---|---|\n");
        for spec in rows {
            let other = win.get(&spec.id).map(|w| keys(w, Platform::Windows));
            let when: Vec<_> = spec
                .default_keys
                .iter()
                .filter(|d| !d.when.is_empty())
                .map(|d| format!("`{}`", cell(d.when)))
                .collect();
            let _ = writeln!(
                s,
                "| {} | {} | {} | {} |",
                cell(&en(&spec.title_key)),
                keys(spec, Platform::Mac),
                other.unwrap_or_default(),
                when.join(", ")
            );
        }
    }
    s
}

fn menu_items(items: &[MenuItem], r: &CommandRegistry<AppCore>, depth: usize, out: &mut String) {
    let indent = "  ".repeat(depth);
    for item in items {
        match item {
            MenuItem::Command { id, label, .. } => {
                let Some(spec) = r.get(&(*id).into()) else {
                    continue;
                };
                let title = en(label.as_deref().unwrap_or(&spec.title_key));
                let keys = keys(spec, Platform::Windows);
                if keys.is_empty() {
                    let _ = writeln!(out, "{indent}- {title}");
                } else {
                    let _ = writeln!(out, "{indent}- {title} — {keys}");
                }
            }
            MenuItem::Submenu { label, items } => {
                let _ = writeln!(out, "{indent}- **{}** ›", en(label));
                menu_items(items, r, depth + 1, out);
            }
            MenuItem::Dynamic(d) => {
                let what = match d {
                    DynamicMenu::RecentWorkspaces => "recent workspaces",
                    DynamicMenu::RecentFiles => "recent files",
                    DynamicMenu::KeptScratchpads => "kept scratchpads",
                    DynamicMenu::PluginCommands => "commands added by plugins",
                    DynamicMenu::PluginEditorContext => "plugin commands",
                };
                let _ = writeln!(out, "{indent}- *({what})*");
            }
            MenuItem::Entry { .. } | MenuItem::Separator => {}
        }
    }
}

fn menus() -> String {
    let r = registry(Platform::Windows);
    let mut s = String::from(HEADER);
    s.push_str("# Menus\n\n");
    s.push_str(
        "The menu bar as it appears on Windows and Linux, with default shortcuts. On macOS the shortcuts use \
         ⌘ instead of Ctrl (see [Keyboard shortcuts](shortcuts.md)), the menus live in the system menu bar, \
         and a **Notoir** menu holds About, Settings and Quit.\n",
    );
    for menu in crate::menus::menu_bar(Platform::Windows) {
        let _ = write!(s, "\n## {}\n\n", en(menu.label));
        menu_items(&menu.items, &r, 0, &mut s);
    }
    s
}

fn commands() -> String {
    let mac = registry(Platform::Mac);
    let win = registry(Platform::Windows);
    let mut s = String::from(HEADER);
    s.push_str("# Commands\n\n");
    s.push_str(
        "Every built-in command. Menus, the toolbar, shortcuts, the [command palette](../command-palette.md), \
         [plugins](../plugin-api.md) and [MCP clients](../mcp.md) all run commands by these ids. Commands marked \
         *hidden* are not listed in the palette; they need arguments and are run from menus, plugins or MCP.\n",
    );
    for (cat, specs) in by_category(&mac) {
        let _ = write!(s, "\n## {}\n\n", en(cat.title_key()));
        s.push_str("| Command | Id | macOS | Windows / Linux |\n|---|---|---|---|\n");
        for spec in specs {
            let other = win.get(&spec.id).map(|w| keys(w, Platform::Windows));
            let title = if spec.palette {
                cell(&en(&spec.title_key))
            } else {
                format!("{} *(hidden)*", cell(&en(&spec.title_key)))
            };
            let _ = writeln!(
                s,
                "| {title} | `{}` | {} | {} |",
                spec.id.as_str(),
                keys(spec, Platform::Mac),
                other.unwrap_or_default()
            );
        }
    }
    s
}

fn value(v: &SettingValue) -> String {
    match v {
        SettingValue::Bool(b) => b.to_string(),
        SettingValue::Int(i) => i.to_string(),
        SettingValue::Float(f) => format!("{f:?}"),
        SettingValue::Str(s) => format!("{s:?}"),
        SettingValue::List(l) => {
            let items: Vec<_> = l.iter().map(|x| format!("{x:?}")).collect();
            format!("[{}]", items.join(", "))
        }
    }
}

fn ty(t: &SettingType) -> String {
    match t {
        SettingType::Bool => "boolean".into(),
        SettingType::Int { min, max } => format!("integer {min}–{max}"),
        SettingType::Float { min, max } => format!("number {min:?}–{max:?}"),
        SettingType::Enum(opts) => opts
            .iter()
            .map(|o| format!("`{o:?}`"))
            .collect::<Vec<_>>()
            .join(" \\| "),
        SettingType::Str => "string".into(),
        SettingType::StrList => "list of strings".into(),
    }
}

fn scopes(d: &SettingDef) -> String {
    let mut s = vec!["user"];
    if d.scopes.workspace {
        s.push("workspace");
    }
    if d.scopes.language {
        s.push("language");
    }
    let mut out = s.join(", ");
    if d.restricted {
        out.push_str(" (trusted workspaces only)");
    }
    out
}

fn settings() -> String {
    let schema = Schema::builtin();
    let mut s = String::from(HEADER);
    s.push_str("# Settings\n\n");
    s.push_str(
        "Every built-in setting with its type, default value and the scopes it can be set at. See \
         [Settings](../settings.md) for where the files live and how scopes combine. Values are written in \
         TOML, for example `editor.fontSize = 16`.\n",
    );
    for &cat in CATEGORIES {
        let defs: Vec<_> = schema.iter().filter(|d| d.category == cat).collect();
        if defs.is_empty() {
            continue;
        }
        let _ = write!(s, "\n## {}\n\n", en(category_key(cat)));
        s.push_str("| Setting | Description | Type | Default | Scopes |\n|---|---|---|---|---|\n");
        for d in defs {
            let key = format!("settings:{}", d.key);
            let title = en(&key);
            let title = if title == key { String::new() } else { title };
            let _ = writeln!(
                s,
                "| `{}` | {} | {} | `{}` | {} |",
                d.key,
                cell(&title),
                ty(&d.ty),
                cell(&value(&d.default)),
                scopes(d)
            );
        }
    }
    s
}

fn mcp_tools() -> String {
    let mut s = String::from(HEADER);
    s.push_str("# MCP tools\n\n");
    s.push_str(
        "The tools Notoir's [MCP server](../mcp.md) offers to AI clients. Each call is checked against the \
         client's permissions for the listed capabilities; *read-only* tools never change anything, and \
         *destructive* tools always ask for approval unless the client is allowed to skip it.\n",
    );
    for t in notoir_mcp::tools::TOOLS {
        let _ = write!(s, "\n## `{}`\n\n{}\n\n", t.name, t.description);
        let caps: Vec<_> = t
            .capabilities
            .iter()
            .map(|c| format!("`{}`", c.key()))
            .collect();
        let mut flags = Vec::new();
        if t.read_only {
            flags.push("read-only");
        }
        if t.destructive {
            flags.push("destructive");
        }
        let _ = writeln!(s, "- Capabilities: {}", caps.join(", "));
        if !flags.is_empty() {
            let _ = writeln!(s, "- {}", flags.join(", "));
        }
        let schema = t.input_schema();
        let required: Vec<&str> = schema["required"]
            .as_array()
            .map(|a| a.iter().filter_map(|v| v.as_str()).collect())
            .unwrap_or_default();
        let props = schema["properties"].as_object();
        match props {
            Some(p) if !p.is_empty() => {
                s.push_str("\n| Parameter | Type | Required | Description |\n|---|---|---|---|\n");
                for (name, p) in p {
                    let ty = match &p["type"] {
                        serde_json::Value::String(t) => t.clone(),
                        serde_json::Value::Array(a) => a
                            .iter()
                            .filter_map(|v| v.as_str())
                            .collect::<Vec<_>>()
                            .join(" or "),
                        _ if p.get("enum").is_some() => "string".into(),
                        _ => "any".into(),
                    };
                    let mut desc = p["description"].as_str().unwrap_or("").to_owned();
                    if let Some(opts) = p["enum"].as_array() {
                        let opts: Vec<_> = opts.iter().map(|o| format!("`{o}`")).collect();
                        if !desc.is_empty() {
                            desc.push(' ');
                        }
                        desc.push_str(&format!("One of {}.", opts.join(", ")));
                    }
                    let _ = writeln!(
                        s,
                        "| `{name}` | {ty} | {} | {} |",
                        if required.contains(&name.as_str()) {
                            "yes"
                        } else {
                            "no"
                        },
                        cell(&desc)
                    );
                }
            }
            _ => s.push_str("\nNo parameters.\n"),
        }
    }
    s
}
